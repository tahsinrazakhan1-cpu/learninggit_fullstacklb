"""Small Python examples for division and remainder operators."""

x, y = -19, 7
print("remainder:", x % y)
print("floor division:", x // y)

value = 7.5
print("division:", value / 2)
print("floor division:", value // 2)
print("remainder:", value % 2)

print("hours in a day:", 26.5 % 24.0)
print("quarters in a whole:", 3.75 % 1.0)
print("24 divided by 6:", 24 // 6.0)